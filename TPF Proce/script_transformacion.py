import numpy as np
import pandas as pd

# 1 Carga del set limpio
df = pd.read_excel('Dataset_limpio.xlsx')

# 2 Copia de trabajo para transformaciones
df_trans = df.copy()

# Superficie no cosechada (Brecha forrajera / Pérdida en hectáreas)
df_trans['superficie_no_cosechada_ha'] = np.maximum(
    0, df_trans['superficie_sembrada_ha'] - df_trans['superficie_cosechada_ha']
)

# Tasa de cosecha porcentual (%)
df_trans['tasa_cosecha_pct'] = np.clip(
    (
        df_trans['superficie_cosechada_ha']
        / df_trans['superficie_sembrada_ha']
    )
    * 100,
    0,
    100,
)

# Eras históricas (Binning temporal con etiquetas simplificadas)
df_trans['periodo_historico'] = pd.cut(
    df_trans['anio'],
    bins=[1922, 1950, 1975, 2000, 2030],
    labels=['Tradicional', 'Expansión', 'Tecnificación', 'S. Directa'],
)

# Región productiva (Pampeana vs. Extrapampeana)
df_trans['region_productiva'] = np.where(
    df_trans['provincia'].isin(
        ['Buenos Aires', 'Córdoba', 'Entre Ríos', 'La Pampa', 'Santa Fe']
    ),
    'Región Pampeana',
    'Extrapampeana',
)

# Exportación a Excel
with pd.ExcelWriter('Dataset_transformado.xlsx', engine='openpyxl') as writer:
  df_trans.to_excel(writer, sheet_name='Datos_Transformados', index=False)

print('¡Transformación completada con éxito!')
print(f'Estructura final: {df_trans.shape[0]} filas y {df_trans.shape[1]} columnas.')